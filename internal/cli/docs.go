package cli

import (
	"encoding/json"
	"fmt"
	"sort"
	"strings"
)

// docs/commands.md is generated from the command table, like the completion
// scripts (make docs; a test keeps it equal to CommandsMarkdown).
// Each docs/i18n/<lang>.json adds docs/commands.<lang>.md: the same layout
// with the translated text. Translations live only there, never in ak.

// docGroups orders the command reference. Every visible command must be in
// one group (a test checks it).
var docGroups = []struct {
	Title    string
	Commands []string
}{
	{"APK", []string{"install", "extract", "signature"}},
	{"App", []string{"info", "permissions", "launch", "kill", "clear", "uninstall", "restart", "activities", "logcat"}},
	{"Screen", []string{"screenshot", "record"}},
	{"Files", []string{"pull"}},
	{"Device", []string{"devices", "mac", "wifi"}},
	{"Setup", []string{"doctor", "completion"}},
}

// docGlobals mirrors the global options and environment in showHelp, plus
// AK_DEBUG.
var docGlobals = [][2]string{
	{"-h, --help", "Show help"},
	{"-v, --version", "Show version"},
	{"--no-color", "Disable colored output"},
}

var docEnv = [][2]string{
	{"ANDROID_SERIAL", "Default target device"},
	{"AK_ADB", "Path to the adb binary"},
	{"NO_COLOR", "Disable colored output"},
	{"AK_DEBUG", "Set to 1 to write a debug log to $TMPDIR/ak-debug.log (AK_DEBUG_LOG changes the path)"},
}

// DocText is every sentence of the command reference. The English one comes
// from the command table; a translation is loaded from JSON.
type DocText struct {
	Language string            `json:"language"` // the language's own name, for the links between pages
	Title    string            `json:"title"`
	Intro    string            `json:"intro"`
	Labels   map[string]string `json:"labels"`   // Contents, Arguments, Options, ...
	Groups   map[string]string `json:"groups"`   // APK, App, ...
	Globals  map[string]string `json:"globals"`  // "-h, --help" -> description
	Env      map[string]string `json:"env"`      // ANDROID_SERIAL -> description
	Commands map[string]DocCmd `json:"commands"` // install -> its text
}

// DocCmd is the text of one command. Flags are keyed like the parser (the
// long name, or the short one when there is none: "--latest", "-r").
type DocCmd struct {
	Summary string            `json:"summary"`
	Long    string            `json:"long"`
	Args    map[string]string `json:"args"`
	Flags   map[string]string `json:"flags"`
}

var docLabels = []string{"Contents", "Global options", "Arguments", "Argument", "Options", "Option",
	"Description", "Examples", "Environment", "Usage", "Generated"}

// englishDocText is the reference as the command table says it.
func englishDocText() DocText {
	t := DocText{
		Language: "English",
		Title:    "ak command reference",
		Intro: "Usage: `ak <command> [options] [arguments]`. Options may come before or after arguments, " +
			"and short options can be combined (`-ea` is `-e -a`). " +
			"Commands that talk to a device pick it with `-s/--serial`, then `$ANDROID_SERIAL`; " +
			"with one device connected it is used, with several you are asked (or `-a/--all` where supported). " +
			"Results go to stdout and messages to stderr. " +
			"Exit codes: 0 success, 1 failure, 2 usage error, 130 interrupted.",
		Labels: map[string]string{
			"Generated": "Generated by `make docs` from the command table. Do not edit.",
		},
		Groups: map[string]string{}, Globals: map[string]string{}, Env: map[string]string{},
		Commands: map[string]DocCmd{},
	}
	for _, l := range docLabels {
		if _, ok := t.Labels[l]; !ok {
			t.Labels[l] = l
		}
	}
	for _, g := range docGroups {
		t.Groups[g.Title] = g.Title
	}
	for _, g := range docGlobals {
		t.Globals[g[0]] = g[1]
	}
	for _, e := range docEnv {
		t.Env[e[0]] = e[1]
	}
	for _, c := range visibleCommands() {
		dc := DocCmd{Summary: c.Summary, Long: c.Long, Args: map[string]string{}, Flags: map[string]string{}}
		for _, a := range c.ArgHelp {
			dc.Args[a[0]] = a[1]
		}
		for _, f := range c.AllFlags() {
			dc.Flags[f.key()] = f.Help
		}
		t.Commands[c.Name] = dc
	}
	return t
}

// CommandsDocs renders docs/commands.md and one docs/commands.<lang>.md per
// translation (translations: lang code -> JSON of docs/i18n/<lang>.json),
// keyed by file name. It fails when a translation misses any text, so a new
// command or option cannot ship untranslated.
func CommandsDocs(translations map[string][]byte) (map[string]string, error) {
	type page struct {
		file string
		text DocText
	}
	pages := []page{{"commands.md", englishDocText()}}
	codes := make([]string, 0, len(translations))
	for code := range translations {
		codes = append(codes, code)
	}
	sort.Strings(codes)
	for _, code := range codes {
		var t DocText
		if err := json.Unmarshal(translations[code], &t); err != nil {
			return nil, fmt.Errorf("i18n/%s.json: %w", code, err)
		}
		if missing := t.missing(); len(missing) > 0 {
			return nil, fmt.Errorf("i18n/%s.json is missing %d entries:\n  %s", code, len(missing), strings.Join(missing, "\n  "))
		}
		pages = append(pages, page{"commands." + code + ".md", t})
	}
	out := map[string]string{}
	for _, pg := range pages {
		var links []string
		for _, other := range pages {
			if other.file == pg.file {
				links = append(links, "**"+other.text.Language+"**")
			} else {
				links = append(links, "["+other.text.Language+"]("+other.file+")")
			}
		}
		out[pg.file] = renderCommandsDoc(pg.text, strings.Join(links, " · "))
	}
	return out, nil
}

// DocSkeleton is the English text as JSON: the starting point of a translation.
func DocSkeleton() string {
	b, _ := json.MarshalIndent(englishDocText(), "", "  ")
	return string(b) + "\n"
}

// missing lists the entries a translation lacks, compared with the English text.
func (t DocText) missing() []string {
	en := englishDocText()
	var m []string
	need := func(ok bool, key string) {
		if !ok {
			m = append(m, key)
		}
	}
	need(t.Language != "", "language")
	need(t.Title != "", "title")
	need(t.Intro != "", "intro")
	for k := range en.Labels {
		need(t.Labels[k] != "", "labels."+k)
	}
	for k := range en.Groups {
		need(t.Groups[k] != "", "groups."+k)
	}
	for k := range en.Globals {
		need(t.Globals[k] != "", "globals."+k)
	}
	for k := range en.Env {
		need(t.Env[k] != "", "env."+k)
	}
	for name, ec := range en.Commands {
		tc, ok := t.Commands[name]
		need(ok, "commands."+name)
		if !ok {
			continue
		}
		need(tc.Summary != "", "commands."+name+".summary")
		need(ec.Long == "" || tc.Long != "", "commands."+name+".long")
		for k := range ec.Args {
			need(tc.Args[k] != "", "commands."+name+".args."+k)
		}
		for k := range ec.Flags {
			need(tc.Flags[k] != "", "commands."+name+".flags."+k)
		}
	}
	sort.Strings(m)
	return m
}

func renderCommandsDoc(t DocText, languages string) string {
	var b strings.Builder
	p := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	L := func(k string) string { return t.Labels[k] }

	p("# %s\n\n", t.Title)
	p("<!-- %s -->\n\n", L("Generated"))
	if strings.Contains(languages, "](") { // only when there is another language
		p("%s\n\n", languages)
	}
	p("%s\n\n", t.Intro)

	p("## %s\n\n", L("Contents"))
	for _, g := range docGroups {
		var links []string
		for _, name := range g.Commands {
			links = append(links, fmt.Sprintf("[%s](#ak-%s)", name, name))
		}
		p("- **%s:** %s\n", t.Groups[g.Title], strings.Join(links, ", "))
	}
	p("- [%s](#%s)\n", L("Global options"), anchor(L("Global options")))

	for _, g := range docGroups {
		for _, name := range g.Commands {
			if c := find(name); c != nil && !c.Hidden {
				writeCommandDoc(&b, c, t)
			}
		}
	}

	p("\n## %s\n\n", L("Global options"))
	p("| %s | %s |\n|---|---|\n", L("Option"), L("Description"))
	for _, r := range docGlobals {
		p("| `%s` | %s |\n", r[0], cell(t.Globals[r[0]]))
	}
	p("\n| %s | %s |\n|---|---|\n", L("Environment"), L("Description"))
	for _, r := range docEnv {
		p("| `%s` | %s |\n", r[0], cell(t.Env[r[0]]))
	}
	return b.String()
}

// anchor is GitHub's heading anchor: lower case, spaces to '-'.
func anchor(heading string) string {
	return strings.ReplaceAll(strings.ToLower(heading), " ", "-")
}

func writeCommandDoc(b *strings.Builder, c *Command, t DocText) {
	p := func(format string, a ...any) { fmt.Fprintf(b, format, a...) }
	L := func(k string) string { return t.Labels[k] }
	dc := t.Commands[c.Name]
	p("\n## ak %s\n\n", c.Name)
	p("%s.\n\n", strings.TrimSuffix(dc.Summary, "."))
	usage := "ak " + c.Name + " [options]"
	if c.Args != "" {
		usage += " " + c.Args
	}
	p("```\n%s\n```\n\n", usage)
	if dc.Long != "" {
		p("%s\n\n", text(dc.Long))
	}
	if len(c.ArgHelp) > 0 {
		p("**%s**\n\n| %s | %s |\n|---|---|\n", L("Arguments"), L("Argument"), L("Description"))
		for _, a := range c.ArgHelp {
			p("| `%s` | %s |\n", codeCell(a[0]), cell(dc.Args[a[0]]))
		}
		p("\n")
	}
	p("**%s**\n\n| %s | %s |\n|---|---|\n", L("Options"), L("Option"), L("Description"))
	for _, f := range c.AllFlags() {
		p("| `%s` | %s |\n", codeCell(strings.TrimSpace(flagLabel(f))), cell(dc.Flags[f.key()]))
	}
	if len(c.Examples) > 0 {
		p("\n**%s**\n\n```bash\n%s\n```\n", L("Examples"), strings.Join(c.Examples, "\n"))
	}
}

// text escapes '<' and '>' so "<file>" is not read as an HTML tag.
func text(s string) string {
	return strings.NewReplacer("<", "&lt;", ">", "&gt;").Replace(s)
}

// cell escapes a markdown table cell.
func cell(s string) string {
	return strings.ReplaceAll(text(s), "|", `\|`)
}

// codeCell escapes a table cell shown as code (no HTML entities there).
func codeCell(s string) string {
	return strings.ReplaceAll(s, "|", `\|`)
}
