package cli

import (
	"fmt"
	"strings"
)

// docs/commands.md is generated from the command table, like the completion
// scripts (make docs; a test keeps it equal to CommandsMarkdown).

// docGroups orders the command reference. Every visible command must be in
// one group (a test checks it).
var docGroups = []struct {
	Title    string
	Commands []string
}{
	{"APK", []string{"install", "extract", "signature"}},
	{"App", []string{"info", "permissions", "launch", "kill", "clear", "uninstall", "restart", "activities", "logcat"}},
	{"Screen", []string{"screenshot", "record"}},
	{"Files", []string{"pull"}},
	{"Device", []string{"devices", "mac", "wifi"}},
	{"Setup", []string{"doctor", "completion"}},
}

// docGlobals mirrors the global options and environment in showHelp, plus
// AK_DEBUG.
var docGlobals = [][2]string{
	{"-h, --help", "Show help"},
	{"-v, --version", "Show version"},
	{"--no-color", "Disable colored output"},
}

var docEnv = [][2]string{
	{"ANDROID_SERIAL", "Default target device"},
	{"AK_ADB", "Path to the adb binary"},
	{"NO_COLOR", "Disable colored output"},
	{"AK_DEBUG", "Set to 1 to write a debug log to $TMPDIR/ak-debug.log (AK_DEBUG_LOG changes the path)"},
}

// CommandsMarkdown returns the English command reference (docs/commands.md).
func CommandsMarkdown() string {
	var b strings.Builder
	p := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }

	p("# ak command reference\n\n")
	p("<!-- Generated by `make docs` from the command table. Do not edit. -->\n\n")
	p("Usage: `ak <command> [options] [arguments]`. Options may come before or after arguments, " +
		"and short options can be combined (`-ea` is `-e -a`). " +
		"Commands that talk to a device pick it with `-s/--serial`, then `$ANDROID_SERIAL`; " +
		"with one device connected it is used, with several you are asked (or `-a/--all` where supported). " +
		"Results go to stdout and messages to stderr. " +
		"Exit codes: 0 success, 1 failure, 2 usage error, 130 interrupted.\n\n")

	p("## Contents\n\n")
	for _, g := range docGroups {
		var links []string
		for _, name := range g.Commands {
			links = append(links, fmt.Sprintf("[%s](#ak-%s)", name, name))
		}
		p("- **%s:** %s\n", g.Title, strings.Join(links, ", "))
	}
	p("- [Global options](#global-options)\n")

	for _, g := range docGroups {
		for _, name := range g.Commands {
			if c := find(name); c != nil && !c.Hidden {
				writeCommandDoc(&b, c)
			}
		}
	}

	p("\n## Global options\n\n")
	p("| Option | Description |\n|---|---|\n")
	for _, r := range docGlobals {
		p("| `%s` | %s |\n", r[0], cell(r[1]))
	}
	p("\n| Environment | Description |\n|---|---|\n")
	for _, r := range docEnv {
		p("| `%s` | %s |\n", r[0], cell(r[1]))
	}
	return b.String()
}

func writeCommandDoc(b *strings.Builder, c *Command) {
	p := func(format string, a ...any) { fmt.Fprintf(b, format, a...) }
	p("\n## ak %s\n\n", c.Name)
	p("%s.\n\n", c.Summary)
	usage := "ak " + c.Name + " [options]"
	if c.Args != "" {
		usage += " " + c.Args
	}
	p("```\n%s\n```\n\n", usage)
	if c.Long != "" {
		p("%s\n\n", text(c.Long))
	}
	if len(c.ArgHelp) > 0 {
		p("**Arguments**\n\n| Argument | Description |\n|---|---|\n")
		for _, a := range c.ArgHelp {
			p("| `%s` | %s |\n", codeCell(a[0]), cell(a[1]))
		}
		p("\n")
	}
	p("**Options**\n\n| Option | Description |\n|---|---|\n")
	for _, f := range c.AllFlags() {
		p("| `%s` | %s |\n", codeCell(strings.TrimSpace(flagLabel(f))), cell(f.Help))
	}
	if len(c.Examples) > 0 {
		p("\n**Examples**\n\n```bash\n%s\n```\n", strings.Join(c.Examples, "\n"))
	}
}

// text escapes '<' and '>' so "<file>" is not read as an HTML tag.
func text(s string) string {
	return strings.NewReplacer("<", "&lt;", ">", "&gt;").Replace(s)
}

// cell escapes a markdown table cell.
func cell(s string) string {
	return strings.ReplaceAll(text(s), "|", `\|`)
}

// codeCell escapes a table cell shown as code (no HTML entities there).
func codeCell(s string) string {
	return strings.ReplaceAll(s, "|", `\|`)
}
